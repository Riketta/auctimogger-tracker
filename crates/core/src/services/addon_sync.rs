//! `addon-sync`: installs or updates the `AuctiMogger` Database addon from
//! a running tracker (`addon/SPEC.md`, section 6.7).
//!
//! The service is the whole use case minus its two edges: the tracker over
//! HTTP and the addon folder on disk are ports, so placement and verification
//! are unit-tested without a network or a filesystem.
//!
//! 1. The addon's own files are read from the manifest and replaced when they
//!    differ from what the folder holds. A slot file is the exception: it
//!    holds a market between syncs, so its placeholder is written only where
//!    no file exists, which is what completes a fresh install.
//! 2. Markets take slots: the explicit placements keep theirs, then every
//!    target the tracker reports, in its order, takes the lowest free slot.
//!    A carrier replaces a slot only after it passed [`verify_carrier`], so a
//!    truncated or foreign download never displaces a working market file.

use std::sync::Arc;

use crate::{
    config::is_valid_target_id,
    domain::DatabaseSnapshot,
    error::SyncError,
    ports::{
        AddonFolderPort,
        ClockPort,
        TrackerAddonPort,
    },
};

/// The addon's folder name inside `Interface/AddOns`, and the name its
/// manifest carries.
pub const ADDON_NAME: &str = "AuctiMoggerDatabase";

/// How many market slots one install has: `Market1.lua` … `Market6.lua`.
pub const SLOT_COUNT: u8 = 6;

/// The first line of every carrier, up to the tracker's version.
pub const CARRIER_BANNER: &str =
    "-- AuctiMogger Database market file - GENERATED by auctimogger-tracker ";

/// How far ahead of the reader's clock a carrier's `generatedAt` may sit
/// before the carrier reads as the work of a diverged generator. It is the
/// addon's own ceiling (`Market.FUTURE_TOLERANCE_SECONDS`): what the game
/// would refuse at load is refused before it replaces a slot file.
pub const CARRIER_FUTURE_TOLERANCE_SECONDS: i64 = 5 * 60;

/// The line that opens a carrier's market header.
const CARRIER_BEGIN: &str = "local m = A.BeginMarket({";
/// The line that closes the market header.
const CARRIER_END: &str = "})";
/// The last line of every carrier.
const CARRIER_CLOSE: &str = "A.EndMarket()";
/// The longest piece of a refused line an error message quotes.
const QUOTE_LIMIT: usize = 60;

/// One file of the addon as the tracker's manifest lists it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ManifestFile {
    /// Path inside the addon folder, `/`-separated.
    pub path: String,
    /// Lower-case hex SHA-256 of the file.
    pub sha256: String,
    /// Size in bytes.
    pub size: u64,
}

/// `GET /api/addon/manifest`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AddonManifest {
    /// The addon's folder name.
    pub addon: String,
    /// The addon's version, as its TOC declares it.
    pub version: String,
    /// The carrier version the addon reads.
    pub feed_version: u32,
    /// Every file, in the tracker's order.
    pub files: Vec<ManifestFile>,
}

/// The market header of one carrier (`addon/SPEC.md`, section 5.2).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CarrierHeader {
    /// The feed version the carrier is written in.
    pub version: i64,
    /// The tracker that generated the carrier.
    pub tracker_version: String,
    /// The market the carrier describes.
    pub target: String,
    /// When the tracker generated it (unix seconds).
    pub generated_at: i64,
}

/// A market bound to a slot.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MarketPlacement {
    /// The slot, `1..=SLOT_COUNT`.
    pub slot: u8,
    /// The tracker's target id.
    pub target: String,
}

/// The result of [`assign_slots`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SlotPlan {
    /// Every market that has a slot, in slot order.
    pub placements: Vec<MarketPlacement>,
    /// The targets that found no free slot.
    pub unplaced: Vec<String>,
}

/// The slot file's path inside the addon folder: `Market1.lua` ….
#[must_use]
pub fn slot_path(slot: u8) -> String {
    format!("Market{slot}.lua")
}

/// The slot a manifest path names, when it is a slot file. Any `Market<N>.lua`
/// with a positive `N` counts, so a placeholder never overwrites a market,
/// whatever slots the tracker's addon carries.
#[must_use]
pub fn slot_of(path: &str) -> Option<u8> {
    let digits = path.strip_prefix("Market")?.strip_suffix(".lua")?;
    let slot = digits.parse::<u8>().ok().filter(|slot| *slot > 0)?;
    (slot_path(slot) == path).then_some(slot)
}

/// Whether a manifest path is a plain addon path: relative, `/`-separated,
/// every component a non-empty name of ASCII letters, digits, `.`, `_` or
/// `-`. Anything else is refused before it is fetched or joined to the addons
/// folder, so no manifest can reach outside the addon.
#[must_use]
pub fn valid_bundle_path(path: &str) -> bool {
    !path.is_empty()
        && path.len() <= 128
        && path.split('/').all(|component| {
            !component.is_empty()
                && component != "."
                && component != ".."
                && component
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-'))
        })
}

/// Binds every market to a slot. The explicit placements keep theirs; then
/// each target of `targets`, in order, that no slot holds yet takes the
/// lowest free one. A target that finds none is reported in
/// [`SlotPlan::unplaced`] rather than dropped silently.
///
/// # Errors
///
/// Returns `SyncError::Placement` when an explicit placement names a slot out
/// of range, claims a slot twice, or places one market twice.
pub fn assign_slots(
    explicit: &[MarketPlacement],
    targets: &[String],
) -> Result<SlotPlan, SyncError> {
    let mut owner: Vec<Option<String>> = vec![None; usize::from(SLOT_COUNT)];
    for placement in explicit {
        if placement.slot == 0 || placement.slot > SLOT_COUNT {
            return Err(SyncError::Placement(format!(
                "slot {} is out of range (1-{SLOT_COUNT}) for market '{}'",
                placement.slot, placement.target
            )));
        }
        if let Some(taken) =
            owner.iter().position(|held| held.as_deref() == Some(placement.target.as_str()))
        {
            return Err(SyncError::Placement(format!(
                "market '{}' is placed twice (slots {} and {})",
                placement.target,
                taken + 1,
                placement.slot
            )));
        }
        let index = usize::from(placement.slot - 1);
        let Some(slot) = owner.get_mut(index) else {
            return Err(SyncError::Placement(format!(
                "slot {} is out of range (1-{SLOT_COUNT})",
                placement.slot
            )));
        };
        if let Some(earlier) = slot.as_deref() {
            return Err(SyncError::Placement(format!(
                "slot {} is claimed by markets '{earlier}' and '{}'",
                placement.slot, placement.target
            )));
        }
        *slot = Some(placement.target.clone());
    }

    let mut plan = SlotPlan { placements: Vec::new(), unplaced: Vec::new() };
    for target in targets {
        // Covers a target an explicit placement named, and a repeated target.
        if owner.iter().any(|held| held.as_deref() == Some(target.as_str())) {
            continue;
        }
        match owner.iter_mut().find(|held| held.is_none()) {
            Some(free) => *free = Some(target.clone()),
            None => plan.unplaced.push(target.clone()),
        }
    }
    for (index, held) in owner.iter().enumerate() {
        if let Some(target) = held {
            plan.placements.push(MarketPlacement {
                slot: u8::try_from(index + 1).unwrap_or(0),
                target: target.clone(),
            });
        }
    }
    Ok(plan)
}

/// Quotes at most [`QUOTE_LIMIT`] characters of a refused line.
fn quoted(line: &str) -> String {
    line.chars().take(QUOTE_LIMIT).collect()
}

/// Reads back what a Lua string literal holds: printable ASCII verbatim, the
/// escapes `\"` and `\\`, and decimal byte escapes. Anything else is refused.
fn lua_unquote(text: &str) -> Option<String> {
    let inner = text.strip_prefix('"')?.strip_suffix('"')?;
    let mut out: Vec<u8> = Vec::with_capacity(inner.len());
    let mut chars = inner.chars();
    let mut buffer = [0u8; 4];
    while let Some(ch) = chars.next() {
        if ch != '\\' {
            // The encoder writes every printable ASCII byte (the space included)
            // verbatim; only the other bytes travel as escapes.
            if !ch.is_ascii_graphic() && ch != ' ' {
                return None;
            }
            out.extend_from_slice(ch.encode_utf8(&mut buffer).as_bytes());
            continue;
        }
        match chars.next()? {
            '"' => out.push(b'"'),
            '\\' => out.push(b'\\'),
            digit => {
                let mut value = digit.to_digit(10)?;
                for _ in 0..2 {
                    match chars.clone().next() {
                        Some(next) if next.is_ascii_digit() => {
                            value = value * 10 + next.to_digit(10)?;
                            chars.next();
                        }
                        _ => break,
                    }
                }
                out.push(u8::try_from(value).ok()?);
            }
        }
    }
    String::from_utf8(out).ok()
}

/// The market header of a carrier: its banner, its closing call and the four
/// fields every carrier carries.
///
/// # Errors
///
/// Returns `SyncError::Verify` when the text is not UTF-8, does not open with
/// the market-file banner, does not end with `A.EndMarket()` (a truncated
/// download), or has no closed market header holding `version`,
/// `trackerVersion`, `target` and `generatedAt`.
pub fn read_carrier_header(bytes: &[u8]) -> Result<CarrierHeader, SyncError> {
    let verify = |message: String| SyncError::Verify(message);
    let text = std::str::from_utf8(bytes)
        .map_err(|_| verify("the carrier is not UTF-8 text".to_owned()))?;
    let mut lines = text.lines();
    match lines.next() {
        Some(first) if first.starts_with(CARRIER_BANNER) => {}
        Some(first) => {
            return Err(verify(format!(
                "the carrier does not open with the market-file banner: {:?}",
                quoted(first)
            )));
        }
        None => return Err(verify("the carrier is empty".to_owned())),
    }
    if !text.trim_end().ends_with(CARRIER_CLOSE) {
        return Err(verify(format!(
            "the carrier is truncated: it does not end with {CARRIER_CLOSE}"
        )));
    }

    let mut fields: Vec<(&str, &str)> = Vec::new();
    let mut in_header = false;
    let mut closed = false;
    for line in lines {
        if !in_header {
            if line == CARRIER_BEGIN {
                in_header = true;
            }
            continue;
        }
        if line == CARRIER_END {
            closed = true;
            break;
        }
        let malformed =
            || verify(format!("a carrier header line is malformed: {:?}", quoted(line)));
        let Some(entry) = line.strip_prefix("    ") else {
            return Err(malformed());
        };
        let Some(entry) = entry.strip_suffix(',') else {
            return Err(malformed());
        };
        let Some((name, value)) = entry.split_once(" = ") else {
            return Err(malformed());
        };
        fields.push((name, value));
    }
    if !in_header {
        return Err(verify("the carrier has no market header".to_owned()));
    }
    if !closed {
        return Err(verify("the carrier's market header is not closed".to_owned()));
    }

    let field =
        |name: &str| fields.iter().find_map(|(key, value)| (*key == name).then_some(*value));
    let number = |name: &str| {
        let value =
            field(name).ok_or_else(|| verify(format!("carrier header field {name} is missing")))?;
        value.parse::<i64>().map_err(|_| {
            verify(format!("carrier header field {name} is not an integer: {value:?}"))
        })
    };
    let string = |name: &str| {
        let value =
            field(name).ok_or_else(|| verify(format!("carrier header field {name} is missing")))?;
        lua_unquote(value).ok_or_else(|| {
            verify(format!("carrier header field {name} is not a string: {value:?}"))
        })
    };
    Ok(CarrierHeader {
        version: number("version")?,
        tracker_version: string("trackerVersion")?,
        target: string("target")?,
        generated_at: number("generatedAt")?,
    })
}

/// Checks a downloaded carrier the way the addon checks it at load
/// (`addon/SPEC.md`, sections 5.2 and 5.9), against the market it was asked
/// for. A carrier that fails here would be refused in game, so it must not
/// replace a working slot file.
///
/// # Errors
///
/// Returns `SyncError::Verify` when the header cannot be read, the carrier is
/// not of the feed version this tool installs, names another market than
/// `expected_target`, carries a target that is not a tracker target id, an
/// empty `trackerVersion`, or a `generatedAt` more than
/// [`CARRIER_FUTURE_TOLERANCE_SECONDS`] ahead of `now`.
pub fn verify_carrier(
    bytes: &[u8],
    expected_target: &str,
    now: i64,
) -> Result<CarrierHeader, SyncError> {
    let header = read_carrier_header(bytes)?;
    let expected_version = i64::from(DatabaseSnapshot::FEED_VERSION);
    if header.version != expected_version {
        return Err(SyncError::Verify(format!(
            "the carrier is feed version {} and this tool installs version {expected_version}",
            header.version
        )));
    }
    if header.target != expected_target {
        return Err(SyncError::Verify(format!(
            "the carrier is for market '{}' and not for '{expected_target}'",
            header.target
        )));
    }
    if !is_valid_target_id(&header.target) {
        return Err(SyncError::Verify(format!(
            "carrier header field target '{}' is not a tracker target id",
            header.target
        )));
    }
    if header.tracker_version.trim().is_empty() {
        return Err(SyncError::Verify("carrier header field trackerVersion is empty".to_owned()));
    }
    let skew = header.generated_at - now;
    if skew > CARRIER_FUTURE_TOLERANCE_SECONDS {
        return Err(SyncError::Verify(format!(
            "generatedAt is {skew} s in the future (a diverged generator: check the clocks)"
        )));
    }
    Ok(header)
}

/// The compact age of the sync's table: the largest of seconds, minutes,
/// hours and days that fits, alone (`45s`, `58m`, `3h`, `2d`). An age below
/// zero reads as zero.
#[must_use]
pub fn format_age(seconds: i64) -> String {
    const MINUTE: i64 = 60;
    const HOUR: i64 = 60 * MINUTE;
    const DAY: i64 = 24 * HOUR;
    let seconds = seconds.max(0);
    if seconds < MINUTE {
        format!("{seconds}s")
    } else if seconds < HOUR {
        format!("{}m", seconds / MINUTE)
    } else if seconds < DAY {
        format!("{}h", seconds / HOUR)
    } else {
        format!("{}d", seconds / DAY)
    }
}

/// Which of the four things a synced file went through.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ChangeKind {
    /// The file differed and was replaced.
    Written,
    /// The folder already held these bytes.
    Unchanged,
    /// The file differs, and a dry run wrote nothing.
    WouldWrite,
    /// The file could not be synced; the folder is as it was.
    Failed,
}

/// What happened to one file.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum FileChange {
    /// The file differed and was replaced.
    Written,
    /// The folder already held these bytes.
    Unchanged,
    /// The file differs, and a dry run wrote nothing.
    WouldWrite,
    /// The file could not be synced, and why; the folder is as it was.
    Failed(String),
}

impl FileChange {
    /// The file's outcome without its failure text.
    #[must_use]
    pub fn kind(&self) -> ChangeKind {
        match self {
            FileChange::Written => ChangeKind::Written,
            FileChange::Unchanged => ChangeKind::Unchanged,
            FileChange::WouldWrite => ChangeKind::WouldWrite,
            FileChange::Failed(_) => ChangeKind::Failed,
        }
    }
}

/// What happened to one addon file of the manifest.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FileOutcome {
    /// The manifest path.
    pub path: String,
    /// The file's size in bytes as the manifest lists it.
    pub bytes: u64,
    /// The outcome.
    pub change: FileChange,
}

/// What happened to one market.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MarketOutcome {
    /// The slot the market was bound to.
    pub slot: u8,
    /// The tracker's target id.
    pub target: String,
    /// The carrier's size in bytes; zero when it could not be fetched.
    pub bytes: u64,
    /// `now - generatedAt` of the carrier, once its header was verified.
    pub age_seconds: Option<i64>,
    /// The outcome.
    pub change: FileChange,
}

/// Everything one run did.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct SyncReport {
    /// The manifest the addon step worked from; `None` under `--no-addon`.
    pub manifest: Option<AddonManifest>,
    /// One row per manifest file; empty under `--no-addon`.
    pub addon: Vec<FileOutcome>,
    /// Whether the addon step was skipped (`--no-addon`).
    pub addon_skipped: bool,
    /// One row per market that has a slot; empty under `--no-markets`.
    pub markets: Vec<MarketOutcome>,
    /// The targets that found no free slot.
    pub unplaced: Vec<String>,
    /// Why the markets could not be listed or placed at all; the rest of the
    /// run stands.
    pub markets_error: Option<String>,
    /// Whether the market step was skipped (`--no-markets`).
    pub markets_skipped: bool,
}

impl SyncReport {
    /// Every failure of the run, one line each: the files and markets that
    /// failed, the markets without a slot, and a target list that could not
    /// be read.
    #[must_use]
    pub fn failures(&self) -> Vec<String> {
        let mut out = Vec::new();
        for file in &self.addon {
            if let FileChange::Failed(reason) = &file.change {
                out.push(format!("file {}: {reason}", file.path));
            }
        }
        for market in &self.markets {
            if let FileChange::Failed(reason) = &market.change {
                out.push(format!("market '{}' in slot {}: {reason}", market.target, market.slot));
            }
        }
        for target in &self.unplaced {
            out.push(format!(
                "market '{target}': no free slot (the addon has {SLOT_COUNT}); choose with --market <target>=<slot>"
            ));
        }
        if let Some(reason) = &self.markets_error {
            out.push(format!(
                "markets not synced: the tracker's target list could not be read or placed: {reason}"
            ));
        }
        out
    }

    /// Whether nothing failed and no market was left without a slot.
    #[must_use]
    pub fn is_clean(&self) -> bool {
        self.failures().is_empty()
    }

    /// How many addon files went through `kind`.
    #[must_use]
    pub fn addon_count(&self, kind: ChangeKind) -> usize {
        self.addon.iter().filter(|file| file.change.kind() == kind).count()
    }

    /// How many markets went through `kind`.
    #[must_use]
    pub fn market_count(&self, kind: ChangeKind) -> usize {
        self.markets.iter().filter(|market| market.change.kind() == kind).count()
    }
}

/// What one run is asked to do.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SyncOptions {
    /// The explicit `--market` placements; they keep their slots.
    pub placements: Vec<MarketPlacement>,
    /// Sync the addon's own files (off: `--no-addon`).
    pub sync_addon: bool,
    /// Sync the market slots (off: `--no-markets`).
    pub sync_markets: bool,
    /// Report what would change and write nothing (`--dry-run`).
    pub dry_run: bool,
}

impl Default for SyncOptions {
    fn default() -> Self {
        Self { placements: Vec::new(), sync_addon: true, sync_markets: true, dry_run: false }
    }
}

/// Refuses a manifest this tool cannot install from.
fn check_manifest(manifest: &AddonManifest) -> Result<(), SyncError> {
    if manifest.addon != ADDON_NAME {
        return Err(SyncError::Verify(format!(
            "the tracker serves its addon as '{}' and this tool installs '{ADDON_NAME}'",
            manifest.addon
        )));
    }
    if manifest.feed_version != DatabaseSnapshot::FEED_VERSION {
        return Err(SyncError::Verify(format!(
            "the tracker serves feed version {} for its addon and this tool installs version {}",
            manifest.feed_version,
            DatabaseSnapshot::FEED_VERSION
        )));
    }
    Ok(())
}

/// Runs `addon-sync` over the two ports.
pub struct AddonSyncService {
    remote: Arc<dyn TrackerAddonPort>,
    folder: Arc<dyn AddonFolderPort>,
    clock: Arc<dyn ClockPort>,
}

impl AddonSyncService {
    /// The service over the tracker, the addon folder and the clock.
    pub fn new(
        remote: Arc<dyn TrackerAddonPort>,
        folder: Arc<dyn AddonFolderPort>,
        clock: Arc<dyn ClockPort>,
    ) -> Self {
        Self { remote, folder, clock }
    }

    /// Runs one sync (`addon/SPEC.md`, section 6.7): the addon's files, then
    /// the markets. Whatever can still run after a failure runs; every
    /// failure is a line of [`SyncReport::failures`].
    ///
    /// # Errors
    ///
    /// Returns `SyncError` only when nothing can be done: the manifest cannot
    /// be read, or names another addon or feed version than this tool
    /// installs.
    pub fn run(&self, options: &SyncOptions) -> Result<SyncReport, SyncError> {
        let mut report = SyncReport {
            addon_skipped: !options.sync_addon,
            markets_skipped: !options.sync_markets,
            ..SyncReport::default()
        };
        if options.sync_addon {
            let manifest = self.remote.manifest()?;
            check_manifest(&manifest)?;
            for file in &manifest.files {
                report.addon.push(self.sync_file(file, options.dry_run));
            }
            report.manifest = Some(manifest);
        }
        if options.sync_markets {
            match self
                .remote
                .market_targets()
                .and_then(|targets| assign_slots(&options.placements, &targets))
            {
                Ok(plan) => {
                    for placement in &plan.placements {
                        report.markets.push(self.sync_market(placement, options.dry_run));
                    }
                    report.unplaced = plan.unplaced;
                }
                Err(error) => report.markets_error = Some(error.to_string()),
            }
        }
        Ok(report)
    }

    /// One addon file: replaced when it differs, and never touching a slot
    /// that already holds a file.
    fn sync_file(&self, file: &ManifestFile, dry_run: bool) -> FileOutcome {
        let failed = |reason: String| FileOutcome {
            path: file.path.clone(),
            bytes: file.size,
            change: FileChange::Failed(reason),
        };
        if !valid_bundle_path(&file.path) {
            return failed(format!("manifest path '{}' is not a plain addon path", file.path));
        }
        if slot_of(&file.path).is_some() {
            // A slot holds a market between syncs: the placeholder is written
            // only where no file exists, which completes a fresh install.
            return match self.folder.read(&file.path) {
                Ok(Some(_)) => FileOutcome {
                    path: file.path.clone(),
                    bytes: file.size,
                    change: FileChange::Unchanged,
                },
                Ok(None) => self.install(file, dry_run),
                Err(error) => failed(error.to_string()),
            };
        }
        self.install(file, dry_run)
    }

    /// Fetches one manifest file and places it.
    fn install(&self, file: &ManifestFile, dry_run: bool) -> FileOutcome {
        let failed = |reason: String| FileOutcome {
            path: file.path.clone(),
            bytes: file.size,
            change: FileChange::Failed(reason),
        };
        let bytes = match self.remote.addon_file(file) {
            Ok(bytes) => bytes,
            Err(error) => return failed(error.to_string()),
        };
        let size = u64::try_from(bytes.len()).unwrap_or(u64::MAX);
        if size != file.size {
            return failed(format!(
                "the download is {size} bytes and its manifest entry says {}",
                file.size
            ));
        }
        let change = match self.place(&file.path, &bytes, dry_run) {
            Ok(change) => change,
            Err(error) => return failed(error.to_string()),
        };
        FileOutcome { path: file.path.clone(), bytes: size, change }
    }

    /// One market: the carrier is verified before it can replace the slot.
    fn sync_market(&self, placement: &MarketPlacement, dry_run: bool) -> MarketOutcome {
        let failed = |bytes: u64, age_seconds: Option<i64>, reason: String| MarketOutcome {
            slot: placement.slot,
            target: placement.target.clone(),
            bytes,
            age_seconds,
            change: FileChange::Failed(reason),
        };
        let bytes = match self.remote.carrier(&placement.target) {
            Ok(bytes) => bytes,
            Err(error) => return failed(0, None, error.to_string()),
        };
        let size = u64::try_from(bytes.len()).unwrap_or(u64::MAX);
        let now = self.clock.now();
        let header = match verify_carrier(&bytes, &placement.target, now) {
            Ok(header) => header,
            Err(error) => return failed(size, None, error.to_string()),
        };
        let age_seconds = now.saturating_sub(header.generated_at);
        let change = match self.place(&slot_path(placement.slot), &bytes, dry_run) {
            Ok(change) => change,
            Err(error) => return failed(size, Some(age_seconds), error.to_string()),
        };
        MarketOutcome {
            slot: placement.slot,
            target: placement.target.clone(),
            bytes: size,
            age_seconds: Some(age_seconds),
            change,
        }
    }

    /// Writes `bytes` over `path` unless the folder already holds them; a
    /// dry run only reports.
    fn place(&self, path: &str, bytes: &[u8], dry_run: bool) -> Result<FileChange, SyncError> {
        match self.folder.read(path)? {
            Some(local) if local == bytes => Ok(FileChange::Unchanged),
            _ if dry_run => Ok(FileChange::WouldWrite),
            _ => {
                self.folder.write(path, bytes)?;
                Ok(FileChange::Written)
            }
        }
    }
}

