//! Feed publication integration: a database snapshot renders through the
//! `FeedRenderer` port into the carrier and its JSON twin, and the publisher
//! persists both atomically.

// Test assertions may unwrap and index: fixture-driven, deterministic inputs.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic, clippy::indexing_slicing)]

use std::{
    collections::BTreeMap,
    path::PathBuf,
    sync::atomic::{
        AtomicU64,
        Ordering,
    },
};

use amtracker_core::{
    domain::{
        Category,
        DatabaseEntry,
        DatabaseSnapshot,
        FeedFormat,
        Flavor,
        ItemRecord,
        ItemRef,
        MarketMeta,
        MetricBlock,
        Span,
        TargetId,
    },
    ports::{
        FeedPublisher,
        FeedRenderer,
    },
};
use amtracker_infra::feed::{
    FeedCodec,
    FileFeedPublisher,
};

fn temp_dir(tag: &str) -> PathBuf {
    static SEQ: AtomicU64 = AtomicU64::new(0);
    let dir = std::env::temp_dir().join(format!(
        "amtracker-feed-{}-{}-{}",
        tag,
        std::process::id(),
        SEQ.fetch_add(1, Ordering::SeqCst)
    ));
    std::fs::create_dir_all(&dir).expect("create temp dir");
    dir
}

fn block(n: i64) -> MetricBlock {
    MetricBlock {
        n,
        min: 100 * n,
        p05: 105 * n,
        p25: 110 * n,
        median: 120 * n,
        p75: 130 * n,
        p95: 140 * n,
        max: 150 * n,
        mad: 8,
        vwap: 121 * n,
        qty_sum: 50 * n,
        listing_count: n,
        sale_rate: Some(0.125),
        sale_rate_180d: None,
        days_since_last_sale: None,
        closures_since_last_sale: None,
        qty_sold: None,
    }
}

/// A record holding nothing but the given spans.
fn record(spans: BTreeMap<Span, MetricBlock>) -> ItemRecord {
    ItemRecord {
        spans,
        live: None,
        value: None,
        sold_count: None,
        expired_count: None,
        supply_days: None,
        low30: None,
        low_rank_30d_bp: None,
        lows: None,
        vendor_price: None,
        craft: None,
        deal: None,
    }
}

/// One market with a listed commodity and a pet species: enough shape for
/// both serializations.
fn sample_snapshot() -> DatabaseSnapshot {
    let mut item_spans = BTreeMap::new();
    item_spans.insert(Span::D1, block(4));
    item_spans.insert(Span::D7, block(9));
    let mut pet_spans = BTreeMap::new();
    pet_spans.insert(Span::D1, block(2));
    DatabaseSnapshot {
        target: TargetId("us-4".into()),
        market: MarketMeta {
            region: Some("us".into()),
            ruleset_id: None,
            house_id: None,
            connected_realm_id: Some(4),
            flavor: Flavor::default(),
        },
        tracker_version: "0.1.0".into(),
        generated_at: 1_760_000_000,
        auctions_at: Some(1_759_999_000),
        commodities_at: None,
        entries: vec![
            DatabaseEntry {
                item: ItemRef::Item { item_id: 194_784 },
                category: Category::Commodity,
                record: record(item_spans),
            },
            DatabaseEntry {
                item: ItemRef::Pet { species: 2546, level: 0, quality: 0, breed: 0 },
                category: Category::Pet,
                record: record(pet_spans),
            },
        ],
    }
}

/// The port answers with the carrier and the twin: the same bytes the pure
/// renderers produce — a Lua chunk opening on the addon's namespace, and a
/// JSON document naming the market.
#[test]
fn the_port_renders_the_carrier_and_its_twin() {
    let snapshot = sample_snapshot();

    let lua = FeedCodec.render(&snapshot, FeedFormat::Lua).expect("render");
    assert_eq!(lua, FeedCodec::carrier(&snapshot).expect("carrier"));
    let text = String::from_utf8(lua).expect("ascii");
    assert!(
        text.starts_with(
            "-- AuctiMogger Database market file - GENERATED by auctimogger-tracker 0.1.0. Do not hand-edit.\n"
        ),
        "{text}"
    );
    assert!(text.contains("local _, A = ...\nlocal m = A.BeginMarket({"), "{text}");
    assert!(text.contains("    target = \"us-4\",\n"), "{text}");
    assert!(text.ends_with("A.EndMarket()\n"), "{text}");
    assert_eq!(
        text.lines().filter(|line| line.starts_with("m.")).count(),
        2,
        "one record line per entry"
    );

    let json = FeedCodec.render(&snapshot, FeedFormat::Json).expect("render");
    assert_eq!(json, FeedCodec::json_twin(&snapshot).expect("twin"));
    let value: serde_json::Value = serde_json::from_slice(&json).expect("valid json");
    assert_eq!(value["version"], 4);
    assert_eq!(value["trackerVersion"], "0.1.0");
    assert_eq!(value["target"], "us-4");
    assert_eq!(value["market"]["connectedRealmId"], 4);
    assert_eq!(value["auctionsAt"], 1_759_999_000);
    assert_eq!(value["items"][0]["itemID"], 194_784);
    assert_eq!(value["items"][0]["category"], "commodity");
    assert_eq!(value["items"][0]["spans"]["d7"]["median"], 1_080);
    assert_eq!(value["items"][1]["speciesID"], 2546);
    assert_eq!(value["items"][1]["category"], "pet");
}

#[test]
fn publisher_writes_files_and_tracks_last_publication() {
    let dir = temp_dir("publish");
    let publisher = FileFeedPublisher::new(dir.join("feeds"));
    let target = TargetId("us-4".into());

    assert!(publisher.last_published(&target, FeedFormat::Lua).expect("last").is_none());

    let snapshot = sample_snapshot();
    let lua = FeedCodec.render(&snapshot, FeedFormat::Lua).expect("render");
    publisher.publish(&target, FeedFormat::Lua, &lua).expect("publish lua");
    let json = FeedCodec.render(&snapshot, FeedFormat::Json).expect("render");
    publisher.publish(&target, FeedFormat::Json, &json).expect("publish json");

    let written = dir.join("feeds").join("us-4").join("feed.lua");
    assert_eq!(std::fs::read(&written).expect("read"), lua);
    let written_json = dir.join("feeds").join("us-4").join("feed.json");
    assert_eq!(std::fs::read(&written_json).expect("read"), json);
    assert_eq!(publisher.read(&target, FeedFormat::Lua).expect("read"), Some(lua.clone()));

    let last = publisher.last_published(&target, FeedFormat::Lua).expect("last").expect("recorded");
    assert_eq!(last.size, lua.len() as u64);
    assert!(last.at > 0);
    assert!(publisher.read(&TargetId("other".into()), FeedFormat::Lua).expect("read").is_none());

    std::fs::remove_dir_all(&dir).ok();
}
